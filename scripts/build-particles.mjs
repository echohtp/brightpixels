import { readFile, writeFile } from 'node:fs/promises';
import tgpu from 'typegpu';
import * as d from 'typegpu/data';

// One schema drives WGSL declarations and the runtime buffer layout.
const fields = { origin: d.vec4f, motion: d.vec4f, style: d.vec4f, color: d.vec4f, drift: d.vec4f };
const Particle = d.struct(fields).$name('Particle');
const Frame = d.struct({ view: d.vec4f }).$name('Frame');
let offset = 0;
const offsets = Object.fromEntries(Object.entries(fields).map(([key, schema]) => {
  const entry = [key, offset]; offset += d.sizeOf(schema) / 4; return entry;
}));
const shader = tgpu.resolve({ externals: { Particle, Frame }, names: 'strict', template: `
@group(0) @binding(0) var<storage, read> particles: array<Particle>;
@group(0) @binding(1) var<uniform> frame: Frame;
struct Output {
  @builtin(position) position: vec4f,
  @location(0) local: vec2f,
  @location(1) color: vec4f,
  @location(2) @interpolate(flat) kind: u32,
  @location(3) fade: f32,
  @location(4) intensity: f32,
};
@vertex fn vertexMain(@builtin(vertex_index) vertex: u32, @builtin(instance_index) instance: u32) -> Output {
  let p = particles[instance];
  let corners = array<vec2f, 6>(vec2f(-3,-3), vec2f(3,-3), vec2f(-3,3), vec2f(-3,3), vec2f(3,-3), vec2f(3,3));
  let local = corners[vertex];
  let age = max(0., frame.view.z - p.motion.x);
  let life = clamp(age / p.motion.y, 0., 1.);
  let center = p.origin.xy + p.origin.zw * age + vec2f(p.drift.x, p.motion.z) * age * age * 0.5;
  let angle = p.style.z + p.motion.w * age;
  let flip = select(1., cos(p.style.z + p.drift.y * age), p.drift.y > 0.);
  let folded = vec2f(local.x, local.y * flip);
  let rotated = vec2f(folded.x * cos(angle) - folded.y * sin(angle), folded.x * sin(angle) + folded.y * cos(angle));
  let pixel = center + rotated * p.style.x;
  var out: Output;
  out.position = vec4f(pixel.x / frame.view.x * 2. - 1., 1. - pixel.y / frame.view.y * 2., 0., 1.);
  out.local = local; out.color = p.color; out.kind = u32(p.style.y);
  out.fade = 1. - smoothstep(0.55, 1., life);
  out.intensity = 1. + (p.style.w - 1.) * frame.view.w;
  return out;
}
@fragment fn fragmentMain(input: Output) -> @location(0) vec4f {
  var distance = length(input.local) - 0.7;
  if (input.kind == 0u) { let q = abs(input.local) - vec2f(0.5, 1.); distance = length(max(q, vec2f(0.))) + min(max(q.x, q.y), 0.); }
  if (input.kind == 1u) { distance = (abs(input.local.x) + abs(input.local.y)) * 0.7 - 0.7; }
  let core = 1. - smoothstep(-0.1, 0.12, distance);
  let halo = exp(-max(distance, 0.) * 2.4) * 0.22;
  let alpha = max(core, halo) * input.fade * input.color.a;
  let light = 1. + (input.intensity - 1.) * core;
  return vec4f(input.color.rgb * light * alpha, alpha);
}
` });
const output = `// Generated by scripts/build-particles.mjs using TypeGPU. Do not edit.\nexport const PARTICLE_FLOATS = ${d.sizeOf(Particle) / 4};\nexport const FRAME_FLOATS = ${d.sizeOf(Frame) / 4};\nexport const OFFSETS = ${JSON.stringify(offsets)};\nexport const PARTICLE_SHADER = ${JSON.stringify(shader)};\n`;
const url = new URL('../particles-shader.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(url, 'utf8') !== output) throw new Error('Particle shader is stale. Run npm run build:particles.');
} else await writeFile(url, output);
